import os
import json
import time
import psycopg2
from kafka import KafkaConsumer

# Configuration Defaults
KAFKA_BOOTSTRAP_SERVERS = os.getenv("KAFKA_BOOTSTRAP_SERVERS", "localhost:9092")
KAFKA_TOPIC = os.getenv("KAFKA_TOPIC", "ads.operational.events")
COCKROACH_HOST = os.getenv("COCKROACH_HOST", "localhost")
COCKROACH_PORT = os.getenv("COCKROACH_PORT", "26257")
COCKROACH_DB = os.getenv("COCKROACH_DB", "netflix_ads")

class CockroachDBContextRetriever:
    """Connects to CockroachDB to pull ground-truth database state for triage context."""
    def __init__(self):
        self.conn_str = f"postgresql://root@{COCKROACH_HOST}:{COCKROACH_PORT}/{COCKROACH_DB}?sslmode=disable"

    def get_campaign_context(self, campaign_id: str) -> dict:
        try:
            conn = psycopg2.connect(self.conn_str)
            cur = conn.cursor()
            cur.execute(
                "SELECT campaign_id, advertiser_name, target_demographic, remaining_budget, target_cpm, active, current_impression_count FROM ad_campaigns WHERE campaign_id = %s",
                (campaign_id,)
            )
            row = cur.fetchone()
            cur.close()
            conn.close()

            if row:
                return {
                    "campaign_id": row[0],
                    "advertiser_name": row[1],
                    "target_demographic": row[2],
                    "remaining_budget": float(row[3]),
                    "target_cpm": float(row[4]),
                    "active": row[5],
                    "current_impression_count": row[6]
                }
        except Exception as e:
            print(f"[CockroachDB] Warning: Unable to query database context ({e})")
        return {}

class AIIncidentTriager:
    """Generates Root Cause Analysis (RCA) and synthesizes JUnit 5 Spring Boot Tests."""

    def triage_incident(self, kafka_event: dict, db_context: dict) -> dict:
        event_type = kafka_event.get("eventType", "UNKNOWN_EVENT")
        campaign_id = kafka_event.get("campaignId", "N/A")

        print(f"\n=======================================================")
        print(f"🤖 [AI-AGENT] INCIDENT TRIAGE TRIGGERED")
        print(f"   Event Type:  {event_type}")
        print(f"   Campaign ID: {campaign_id}")
        print(f"   Kafka Event Payload: {json.dumps(kafka_event)}")
        print(f"   CockroachDB Ground Truth: {json.dumps(db_context)}")
        print(f"=======================================================\n")

        # Perform RCA Reasoning
        rca_summary = self._generate_rca(event_type, kafka_event, db_context)
        junit_test_code = self._generate_junit_test(event_type, campaign_id, db_context)

        return {
            "campaign_id": campaign_id,
            "rca_summary": rca_summary,
            "junit_test_code": junit_test_code
        }

    def _generate_rca(self, event_type: str, event: dict, context: dict) -> str:
        if event_type == "AD_BUDGET_EXHAUSTED_ANOMALY":
            remaining = context.get("remaining_budget", event.get("remainingBudget", 0))
            is_active = context.get("active", event.get("active", False))
            return (
                f"ROOT CAUSE ANALYSIS (RCA):\n"
                f"- Primary Anomaly: Ad request rejected for campaign '{event.get('campaignId')}'.\n"
                f"- Diagnosis: Advertiser '{event.get('advertiser')}' has a remaining budget of ${remaining} "
                f"and active status flag set to '{is_active}'.\n"
                f"- Recommendation: Verify automated budget refresh triggers in CockroachDB or notify advertiser."
            )
        else:
            return f"ROOT CAUSE ANALYSIS (RCA):\n- Anomaly Detected: {event_type} for Campaign '{event.get('campaignId')}'."

