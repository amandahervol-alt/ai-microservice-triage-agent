def save_generated_test(test_code: str, campaign_id: str):
    output_dir = os.path.join("..", "ad-service", "src", "test", "java", "com", "netflix", "ads", "generated")
    os.makedirs(output_dir, exist_ok=True)
    safe_id = campaign_id.replace("-", "_") if campaign_id != "N/A" else "Unknown"
    filename = os.path.join(output_dir, f"AdServingRegression_{safe_id}Test.java")

    with open(filename, "w", encoding="utf-8") as f:
        f.write(test_code)

    print(f"✨ [AI-AGENT] AUTO-GENERATED JUNIT TEST SAVED TO: {filename}\n")

def run_agent():
    print(f"🚀 Starting Netflix Ads AI Triage Agent...")
    print(f"Listening to Kafka broker: {KAFKA_BOOTSTRAP_SERVERS}, Topic: {KAFKA_TOPIC}\n")

    retriever = CockroachDBContextRetriever()
    triager = AIIncidentTriager()

    while True:
        try:
            consumer = KafkaConsumer(
                KAFKA_TOPIC,
                bootstrap_servers=KAFKA_BOOTSTRAP_SERVERS,
                value_deserializer=lambda m: json.loads(m.decode("utf-8")),
                auto_offset_reset="latest",
                group_id="netflix-ai-triage-group"
            )
            print("✅ Connected to Kafka topic successfully. Awaiting operational events...")

            for message in consumer:
                event = message.value
                campaign_id = event.get("campaignId", "")
                
                # Fetch CockroachDB Context
                db_context = retriever.get_campaign_context(campaign_id) if campaign_id else {}
                
                # Run AI Triage & Test Gen
                result = triager.triage_incident(event, db_context)
                
                # Save generated test file
                save_generated_test(result["junit_test_code"], result["campaign_id"])

        except Exception as e:
            print(f"⏳ Waiting for Kafka broker ({e}). Retrying in 5s...")
            time.sleep(5)

if __name__ == "__main__":
    run_agent()
